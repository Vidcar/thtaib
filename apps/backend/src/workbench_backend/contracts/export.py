"""Deterministic OpenAPI and JSON Schema export from canonical Pydantic models."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter

from workbench_backend.contracts.auth import LocalSessionTrustContract
from workbench_backend.contracts.lifecycle import RunLifecycleContract, RunLifecycleStatus
from workbench_backend.interaction.schemas import InteractionRecovery, WorkbenchInteractionMetadata
from workbench_backend.contracts.paths import (
    JSONSCHEMA_MODELS,
    MANIFEST_RELATIVE,
    OPENAPI_RELATIVE,
    jsonschema_relative,
)
from workbench_backend.contracts.schema_app import create_shared_contract_app

GENERATED_COMMENT = (
    "GENERATED by workbench_backend.contracts — do not hand-edit. "
    "Regenerate with the registered shared-contract command."
)

_SCHEMA_MODELS = {
    "LocalSessionTrustContract": LocalSessionTrustContract,
    "RunLifecycleContract": RunLifecycleContract,
    "RunLifecycleStatus": RunLifecycleStatus,
    "InteractionRecovery": InteractionRecovery,
    "WorkbenchInteractionMetadata": WorkbenchInteractionMetadata,
}


def stable_json_bytes(payload: Any) -> bytes:
    return (json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=True) + "\n").encode(
        "utf-8"
    )


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def build_openapi_document() -> dict[str, Any]:
    document = create_shared_contract_app().openapi()
    document.setdefault("info", {})
    document["info"]["x-workbench-generated"] = GENERATED_COMMENT
    return document


def build_json_schema(model_name: str) -> dict[str, Any]:
    if model_name not in _SCHEMA_MODELS:
        raise KeyError(f"unknown shared-contract schema: {model_name}")
    target = _SCHEMA_MODELS[model_name]
    if isinstance(target, type) and issubclass(target, BaseModel):
        schema = target.model_json_schema()
    else:
        schema = TypeAdapter(target).json_schema()
    schema["$comment"] = GENERATED_COMMENT
    return schema


def write_python_artifacts(repo_root: Path) -> dict[str, bytes]:
    artifacts: dict[str, bytes] = {
        OPENAPI_RELATIVE: stable_json_bytes(build_openapi_document()),
    }
    for name in JSONSCHEMA_MODELS:
        artifacts[jsonschema_relative(name)] = stable_json_bytes(build_json_schema(name))
    for relative, payload in artifacts.items():
        target = repo_root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)
    return artifacts


def write_manifest(
    repo_root: Path,
    *,
    file_digests: dict[str, str],
    openapi_typescript: str,
) -> bytes:
    payload = {
        "$comment": GENERATED_COMMENT,
        "generator": {
            "openapi_typescript": openapi_typescript,
            "source": "apps/backend/src/workbench_backend/contracts",
        },
        "files": dict(sorted(file_digests.items())),
    }
    data = stable_json_bytes(payload)
    target = repo_root / MANIFEST_RELATIVE
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)
    return data
